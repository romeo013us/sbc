'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { execFileSync, spawnSync } = require('node:child_process');
const script = path.resolve(__dirname, '../scripts/pin-verified-godaddy-ref.sh');

test('a tested source gets one recovery ref, and a different tree cannot replace it', t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'sbc-pin-'));
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  const git = (...args) => execFileSync('git', args, { cwd: dir, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();
  git('init', '-q', '-b', 'source');
  git('init', '-q', '--bare', 'remote.git');
  git('remote', 'add', 'origin', path.join(dir, 'remote.git'));
  git('config', 'user.name', 'SBC test');
  git('config', 'user.email', 'fixture@example.invalid');
  git('commit', '--allow-empty', '-qm', 'source');
  const source = git('rev-parse', 'HEAD');
  git('push', 'origin', 'source');
  const compile = value => {
    fs.writeFileSync(path.join(dir, 'runtime'), value);
    git('add', 'runtime');
    git('commit', '-qm', value);
  };
  const pin = (sha = source) => spawnSync('bash', [script, sha], { cwd: dir, encoding: 'utf8' });
  const remote = ref => git('--git-dir=remote.git', 'rev-parse', ref);
  const ref = 'refs/heads/release/verified-godaddy-' + source;
  compile('first');
  const first = git('rev-parse', 'HEAD');
  assert.equal(pin().status, 0);
  assert.equal(remote(ref), first);
  git('commit', '--amend', '-qm', 'repeat build with identical tree');
  assert.notEqual(git('rev-parse', 'HEAD'), first);
  assert.equal(pin().status, 0);
  git('switch', '--detach', source);
  compile('different');
  assert.notEqual(pin().status, 0);
  assert.notEqual(pin(first).status, 0);
  assert.notEqual(pin('other').status, 0);
  assert.equal(remote(ref), first);
  assert.equal(remote('refs/heads/source'), source);
});
test('the stable Preview branch advances only to a canonical compiled release with matching pinned bytes',t=>{
  const dir=fs.mkdtempSync(path.join(os.tmpdir(),'sbc-preview-'));
  t.after(()=>fs.rmSync(dir,{recursive:true,force:true}));
  const run=(name,args)=>spawnSync(name,args,{cwd:dir,encoding:'utf8'});
  const git=(...args)=>{const r=run('git',args);assert.equal(r.status,0,r.stderr);return r.stdout.trim();};
  git('init','-q','-b','a-sbc-master');git('init','-q','--bare','remote.git');
  git('remote','add','origin',path.join(dir,'remote.git'));git('config','user.name','SBC test');git('config','user.email','fixture@example.invalid');
  const build=label=>{git('commit','--allow-empty','-qm',label);return git('rev-parse','HEAD');};
  const source=build('source'),release=build('compiled');
  git('push','origin','a-sbc-master');
  const advance=sha=>run('bash',[path.join(path.dirname(script),'advance-verified-preview.sh'),sha]);
  assert.notEqual(advance(source).status,0,'missing pin');
  assert.equal(run('bash',[script,source]).status,0);
  assert.equal(advance(source).status,0);
  const live=()=>git('--git-dir=remote.git','rev-parse','refs/heads/deploy/godaddy-verified-preview');
  assert.equal(live(),release);
  const next=build('subsequent source');git('push','origin','a-sbc-master');
  assert.equal(advance(source).status,0);assert.equal(live(),release);
  const second=build('new compiled');git('push','origin','a-sbc-master');
  assert.equal(run('bash',[script,next]).status,0);
  assert.equal(advance(next).status,0);assert.equal(live(),second);
});
