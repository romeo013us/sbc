'use strict';
const {test}=require('node:test'),assert=require('node:assert/strict');
const fs=require('node:fs/promises'),os=require('node:os'),path=require('node:path');
const {createHash}=require('node:crypto');
const {createLocalMediaRenderer}=require('../enterprise/creative-intelligence/local-media.cjs');
const {stageSocialJpeg}=require('../enterprise/creative-intelligence/social-jpeg.cjs');
const {buildSocialRelease}=require('../enterprise/creative-intelligence/social-release.cjs');
const hash=b=>createHash('sha256').update(b).digest('hex');
test('verified JPEG release requires exact final-byte approval and fresh source; emits no private identifiers',async t=>{
 const root=await fs.mkdtemp(path.join(os.tmpdir(),'sbc-social-release-'));t.after(()=>fs.rm(root,{recursive:true,force:true}));
 const ffmpeg='/usr/bin/ffmpeg',ffprobe='/usr/bin/ffprobe',render=createLocalMediaRenderer({ffmpeg,ffprobe});
 const input=await render.renderImage({format:'square',palette:'midnight',brand:'SBC',headline:'Build your business',detail:'Invest in your future',cta:'Talk to us'});
 const logo=await render.renderImage({format:'square',palette:'ink',brand:'Fixture',headline:'Test logo',detail:'Test only',cta:'Test'});
 const logoPath=path.join(root,'logo.png');await fs.writeFile(logoPath,logo.bytes);
 let state='approved',version=1;
 const item={asset:{id:'a'.repeat(64),tenantId:7,projectId:'sbc-marketing',mime:'image/png',sha256:hash(input.bytes),alt:'Business growth campaign'},bytes:input.bytes};
 const reviews={get:()=>({state,version,assetId:item.asset.id}),exportApproved:async()=>{if(state!=='approved')throw Error('REVIEW_REQUIRED');return item;}};
 const options={reviews,tenantId:7,ffmpeg,ffprobe,logoPath,logoSha256:hash(logo.bytes),outputRoot:root};
 const stage=await stageSocialJpeg({...options,jobId:'private-job'});
 const entry={jobId:'private-job',approvedSha256:stage.sha256,reviewVersion:1};
 const release=await buildSocialRelease({...options,entries:[entry],priorSourceIds:[]});
 assert.equal(release.publicationReady,false);assert.equal(release.manifest.entries.length,1);
 const record=release.manifest.entries[0];assert.equal(record.sha256,stage.sha256);assert.equal(record.url,'https://sbcmia.com/assets/social/campaigns/'+stage.sha256+'.jpg');
 assert.equal(hash(release.files['assets/social/campaigns/'+stage.sha256+'.jpg']),stage.sha256);
 assert.equal(release.zip.readUInt32LE(0),0x04034b50);
 assert(!JSON.stringify(release.manifest).includes('private-job'));assert(!JSON.stringify(release.manifest).includes(item.asset.id));
 await assert.rejects(buildSocialRelease({...options,entries:[{...entry,approvedSha256:'0'.repeat(64)}],priorSourceIds:[]}),/SOCIAL_FINAL_APPROVAL_REQUIRED/);
 await assert.rejects(buildSocialRelease({...options,entries:[entry],priorSourceIds:[item.asset.id]}),/SOCIAL_CREATIVE_REUSED/);
 version=2;await assert.rejects(buildSocialRelease({...options,entries:[entry],priorSourceIds:[]}),/SOCIAL_FINAL_APPROVAL_REQUIRED/);
 state='rejected';await assert.rejects(buildSocialRelease({...options,entries:[entry],priorSourceIds:[]}),/REVIEW_REQUIRED/);
});
