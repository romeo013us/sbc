'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'..'),read=p=>fs.readFileSync(path.join(root,p),'utf8');
const training=require('../enterprise/training-system-v2.js');
const reader=require('../public/sbc-research-lesson-reader.js');
const user={id:'lorna-training-fixture',username:'lorna',name:'Lorna',role:'lead_researcher',active:true};
const db={users:[user],settings:{}};
const data=training.getForUser(db,user);
assert.ok(data.assigned.length>0,'Lorna must have real assigned training');
const course=data.assigned.find(x=>x.course.id==='role-lead_researcher-v1')||data.assigned[0];
assert.ok(course.course.modules.length>0,'assigned course must contain lessons');
const lessonModule=course.course.modules[0];
const lesson=reader.normalize(lessonModule);
assert.ok(lesson.hasReadableContent,'actual lesson material must be readable');
assert.ok(lesson.objective.length>10,'real objective must appear');
assert.ok(lesson.learn.length>=1,'real teaching points must appear');
assert.ok(lesson.practicePrompt.length>10,'real practice must appear');
assert.ok(lesson.knowledgePrompt.length>10,'real knowledge check must appear');
assert.ok(lesson.questions.length>=1,'assessment preparation should include actual prompts');
const normal=reader.normalize({id:'test',title:'Safety',lesson:{objective:'Understand verified research',learn:['Confirm public source'],practice:{prompt:'Research a verified business'},knowledgeCheck:{prompt:'Explain the verification rule'}},status:'published'});
assert.deepEqual(normal.learn,['Confirm public source']);
assert.ok(normal.hasReadableContent);
const missing=reader.normalize({id:'missing',title:'Content missing',description:'',lesson:{}});
assert.equal(missing.hasReadableContent,false,'empty lessons cannot be marked complete');
const html=read('public/lead-research.html'),js=read('public/lead-research.js'),css=read('public/lead-research.css');
new vm.Script(js,{filename:'public/lead-research.js'});
new vm.Script(read('public/sbc-research-lesson-reader.js'),{filename:'public/sbc-research-lesson-reader.js'});
assert.ok(html.includes('data-tab="today"'),'daily task navigation absent');
assert.ok(html.includes('data-pane="today"'),'daily task section absent');
assert.ok(html.includes('id="daily-task-list"'));
assert.ok(html.includes('sbc-research-lesson-reader.js?v=3'));
assert.ok(html.indexOf('sbc-research-lesson-reader.js?v=3')<html.indexOf('lead-research.js?v=3'),'reader helper must load before UI');
assert.match(js,/lessonContent\(content,mod,course\.id,status\)/,'click must show full lesson body');
assert.match(js,/var reader=window\.SBCResearchLessonReader/);
assert.match(js,/trainingParagraph\(parent,'Lesson objective'/);
assert.match(js,/trainingParagraph\(parent,'Practice exercise'/);
assert.match(js,/trainingParagraph\(parent,'Knowledge check'/);
assert.match(js,/lesson\.learn\.forEach/);
assert.match(js,/button\.textContent=opening\?'Close lesson':'Open lesson'/);
assert.match(js,/if\(!lesson\.hasReadableContent\)/);
assert.match(js,/if\(answer\.length<12\|\|!check\.checked\)return/);
assert.match(js,/submit\.disabled=!check\.checked\|\|reflection\.value\.trim\(\)\.length<12/);
assert.match(js,/api\('\/api\/training\/progress'/);
assert.match(js,/courseId:courseId,moduleId:mod\.id,status:'completed',evidence:answer/);
assert.ok(!js.includes("'Mark lesson complete'"),'old blind completion control must be removed');
assert.ok(!js.includes('window.location.reload('),'training navigation must not reload dashboard');
assert.match(js,/function renderDailyPlan\(\)/);
for(const tag of ['Find new business prospects','Add complete researched lists','Handle only automatic-verification exceptions','Finish a short Academy lesson','Reach your 16–20 research goal and hand off'])assert.ok(js.includes(tag),'daily task missing '+tag);
assert.match(js,/themes=\{Monday:/,'daily focus rotation missing');
assert.match(js,/timeZone:'America\/New_York'/,'daily plan must follow SBC Eastern business day');
assert.match(js,/setTab\(item\.tab\)/,'daily action buttons must open real workspace screens');
assert.match(css,/\.training-lesson-content/);
assert.match(css,/\.daily-task-row/);
assert.match(css,/\.lesson-ack input/);
console.log('[SBC LORNA TRAINING + DAILY TASKS] PASS: real published role course, full lesson content, gated explicit completion, 5 work blocks, responsive UI, no backend access expansion.');
