'use strict';
const assert=require('node:assert/strict');
const {evaluate,domains,mustPass}=require('./sbc-strict-95-release-scorecard.cjs');
const sha='0'.repeat(40);
let empty=evaluate({commit:sha});
assert.equal(empty.status,'NO_GO');
for(const name of ['company','saas','build'])assert.equal(empty.sections[name].verifiedPoints,0);
const make=()=>Object.fromEntries(Object.entries(domains).map(([name,checks])=>[name,Object.fromEntries(checks.map(([id])=>[id,{verified:true,observedAt:'2026-10-25T14:00:00Z',evidence:'Owner/provider independent verification ticket'}]))]));
const complete={commit:sha,...make()};
assert.equal(evaluate(complete).status,'ELIGIBLE_FOR_OWNER_FINAL_REVIEW');
delete complete.company.confirmed_paid_sales.evidence;
assert.equal(evaluate(complete).status,'NO_GO','unverified paid revenue may never receive a passing 9.5');
complete.company.confirmed_paid_sales.evidence='Verified provider record and accounting evidence';
delete complete.saas.tested_backup_restore.evidence;
assert.equal(evaluate(complete).status,'NO_GO','missing restore test blocks certification');
complete.saas.tested_backup_restore.evidence='Read-only restore drill audit attachment';
complete.commit='unverified';
assert.equal(evaluate(complete).status,'NO_GO','release SHA must be identified');
assert.equal(mustPass.length>=6,true);
console.log('SBC strict Company + SaaS + Build 95/100 evidence gate: missing proof fails closed PASS');