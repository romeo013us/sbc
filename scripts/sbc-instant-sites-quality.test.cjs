'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'..'),read=p=>fs.readFileSync(path.join(root,p),'utf8');
const Factory=require('../enterprise/sbc-prospect-site-factory.cjs');
const demo=businessName=>({id:'d-'+businessName.toLowerCase().replace(/\W+/g,'-'),slug:'demo-'+businessName.toLowerCase().replace(/\W+/g,'-'),offerTier:'essentials',industry:'Barber shop',status:'Draft',customer:{businessName,city:'Miami'}});
const first=Factory.define(demo('Apex Barber'));
assert.equal(first.style.category,'beauty');
assert.match(first.designVariant,/^beauty-[1-3]$/);
assert.equal(first.designVariant,Factory.define(demo('Apex Barber')).designVariant,'same business must have stable no-AI design');
const brands=['Apex Barber','Midtown Grooming','Golden Blades','Neon Cuts','Prestige Fade','Barber Headquarters','Kingdom Barber'];
const themes=new Set(brands.map(b=>Factory.define(demo(b)).designVariant));
assert(themes.size>=2,'a whole industry must not receive the exact same brand theme');
const palettes=new Set(brands.map(b=>Factory.define(demo(b)).style.p));
assert(palettes.size>=2,'no paid AI should be necessary for distinct color systems');
const a=Factory.renderPage(demo('Apex Barber'),'home');
const b=Factory.renderPage(demo('Midtown Grooming'),'home');
assert.match(a,/data-sbc-design-variant="beauty-/);
assert.notEqual(a,b);
assert.match(a,/<meta name="description"/);
assert.match(a,/noindex,nofollow,noarchive/,'private concept cannot accidentally index');
assert.match(a,/alt="Example stock photo/,'illustrative imagery must not masquerade as actual client images');
const workerSource=read('public/sbc-account-success-v1.js');
const context={window:{}};
vm.runInNewContext(workerSource,context);
const audit=context.window.SBC_ACCOUNT_SUCCESS.siteQuality;
assert.equal(typeof audit,'function');
const report=audit(demo('Apex Barber'),{businessName:'Apex Barber',industry:'Barber shop'});
assert.equal(report.readyToPublish,false,'an unreviewed draft must never be called launch ready');
assert.equal(report.score,null,'do not invent a 9.5 score for an unmeasured site');
for(const label of ['Content accuracy','Media rights','Accessibility','Mobile performance','SEO','Functional forms','Hosting & SSL','Customer approval'])assert(report.checks.some(x=>x.label===label),'missing quality dimension '+label);
assert(report.checks.every(x=>x.state==='pending'||x.state==='not_measured'),'do not claim automatic approval');
const approved=audit({status:'Approved',verifiedBusinessDetails:{verified:true,services:['Haircut'],phone:'3055555555'}},{businessName:'Apex Barber',industry:'Barber'});
assert.equal(approved.readyToPublish,false,'proposal approval and a couple verified facts are not hosting/payment/form readiness');
assert(approved.checks.some(c=>c.state==='not_measured'),'real performance measurements still required');
const generator=read('public/sbc-website-production-v1.js');
assert.match(generator,/SBC_ACCOUNT_SUCCESS/,'quality system must use the shared account module');
assert.match(generator,/engine\.siteQuality\(/,'quality standard must be called within website-production interface');
assert.match(generator,/Site launch quality gate/);
assert.equal(generator,read('browser_public/sbc-website-production-v1.js'));
assert.equal(workerSource,read('browser_public/sbc-account-success-v1.js'));
new vm.Script(generator);
console.log('PASS: deterministic multi-theme Instant Sites, no fabricated grades, launch quality gates, noindex and preview honesty');