assert(updated.includes("manualMode?x.manualDial===true"));
assert(updated.includes("&&Boolean(x.manualDial)===manualDial"));
assert(updated.includes('VOICE_LOG_MYSQL_NOT_DURABLE'),'existing durable log gate must remain');
assert(updated.includes("sbcSignedTwimlV6619"),'signed Twilio webhook must remain');
assert.equal(updated.split("app.post('/api/voice/log',auth").length-1,1);
if(process.argv.includes('--staged')){
 assert.equal(updated,server,'staged server must contain manual patch');
 const markCount=server.split(patch.MARK).length-1;
 assert.equal(markCount,1,'manual patch marker should occur exactly once');
}
