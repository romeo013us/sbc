'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const ROOT=path.resolve(__dirname,'..');
const front=require('../public/sbc-manual-dialer-v6696.js');
const patch=require('./v6696-stage-manual-dialer.cjs');
const read=p=>fs.readFileSync(path.join(ROOT,p),'utf8');
const html=read('public/index.html'),mirrorHtml=read('browser_public/index.html');
const js=read('public/sbc-manual-dialer-v6696.js'),mirrorJs=read('browser_public/sbc-manual-dialer-v6696.js');
const css=read('public/sbc-manual-dialer-v6696.css'),mirrorCss=read('browser_public/sbc-manual-dialer-v6696.css');
