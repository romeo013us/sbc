assert.equal(payload.notes,item.notes);assert.equal(payload.status,'connecting');
assert(/data-digit/.test(js)&&/sbcManualCall/.test(js)&&/sbcManualEnd/.test(js)&&/sendDigits/.test(js));
assert(!/\/api\/customers|\/api\/crm\/leads/.test(js),'manual dialer may not modify the leads/customer API');
