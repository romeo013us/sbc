'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..'),read=p=>fs.readFileSync(path.join(root,p),'utf8');
const js=read('public/sbc-command-center-focus-v1.js');
const css=read('public/sbc-command-center-focus-v1.css');
const html=read('public/index.html');
const owner=read('public/app.js');
assert.match(html,/sbc-command-center-focus-v1\.js/,'focused navigation must load');
assert.match(html,/sbc-command-center-focus-v1\.css/,'focused styling must load');
for(const view of ['dashboard','customers','callcenter','orders','acquisition','workforce','metrics'])assert.ok(js.includes("view:'"+view+"'"),'missing daily navigation route '+view);
assert.ok(js.includes("sbc-website-production-nav"),'existing website production must remain accessible');
assert.ok(js.includes("sbcAdvancedNav"),'all original modules must remain in More tools');
assert.ok(js.includes("groups.appendChild(child)"),'old groups must relocate, not be deleted');
assert.ok(js.includes("sbcFocusToggle"),'owner can switch to full toolset');
assert.ok(js.includes("sbcNavigate"),'new buttons use canonical navigation');
assert.ok(!js.includes("element.remove()"),'no feature deletion by the focus system');
assert.match(css,/data-sbc-focus-mode="focus"/,'compact mode must keep potentially noisy overlays out of daily work');
assert.match(css,/sbcAgentOSPanel/,'agent OS controls must remain available in full mode');
assert.match(owner,/SBC_LEAD_PROFILE/,'sales links must use shared account profiles');
for(const file of ['sbc-command-center-focus-v1.js','sbc-command-center-focus-v1.css','index.html'])assert.equal(read('public/'+file),read('browser_public/'+file),'release mirror mismatch: '+file);
new(require('node:vm').Script)(js,{filename:'sbc-command-center-focus-v1.js'});
console.log('PASS focused Command Center UX: 8 daily routes, more tools, reversible full mode, no deletion, preserved links and mirrored assets');
