'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const runtime=require('../enterprise/kevin/kevin-runtime.cjs');
const veto=require('../enterprise/kevin/owner-veto-store.cjs');
let recovery=true;
assert.equal(runtime.recoveryRequiredNow(()=>recovery),true,'callback must detect active recovery');
recovery=false;
assert.equal(runtime.recoveryRequiredNow(()=>recovery),false,'callback must not stay truthy after recovery clears');
assert.equal(runtime.recoveryRequiredNow(false),false,'literal false must remain false');
assert.equal(runtime.recoveryRequiredNow(true),true,'literal true must remain true');
assert.equal(runtime.recoveryRequiredNow(null),false);
const src=fs.readFileSync(path.resolve(__dirname,'../enterprise/kevin/kevin-runtime.cjs'),'utf8');
assert(src.includes('if (recoverySafe()) {'),'heartbeat must evaluate active recovery');
assert(!src.includes('if (recoveryRequired) {'),'do not test a recovery callback as a boolean');
assert(src.includes("runtime.intervalHandle = null;"),'active recovery must suspend heartbeat');
assert(src.includes("runtime.stop = () => {};"),'active recovery stays read-only');
assert(src.includes("ownerVetoActive:vetoReceipt.active"),'owner veto must persist');
const missing=veto.read(path.join(__dirname,'this-is-not-a-real-dir'));
assert.equal(missing.reason,'NO_RECEIPT');
assert.equal(missing.active,true,'missing veto receipt must fail closed');
assert.equal(missing.verified,false);
console.log('PASS Kevin callback checked as live boolean; recovery still fail-closed; owner veto receipt separate from GoDaddy deployment.');
