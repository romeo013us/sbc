'use strict';
const {test}=require('node:test');
const assert=require('node:assert/strict');
const {createPool}=require('mysql2/promise');
const {createDurableMarketCycle}=require('../enterprise/sbc-market-intelligence.cjs');
const states='AL AK AZ AR CA CO CT DE DC FL GA HI ID IL IN IA KS KY LA ME MD MA MI MN MS MO MT NE NV NH NJ NM NY NC ND OH OK OR PA RI SC SD TN TX UT VT VA WA WV WI WY'.split(' ');
test('real isolated MySQL: cross-instance lock, restart schedule, evidence projection and writer revocation',async()=>{
 assert.equal(process.env.SBC_MARKET_DISPOSABLE_CI,'1');
 assert.ok(process.env.SBC_MARKET_CI_PASSWORD);
 const config={host:'127.0.0.1',port:3306,user:'root',password:process.env.SBC_MARKET_CI_PASSWORD,database:'sbc_market_ci',connectionLimit:2,timezone:'Z'};
 const a=createPool(config),b=createPool(config);
 let now=Date.parse('2026-11-28T12:00:00Z'),writable=true,calls=0,release,started;
 const ready=new Promise(r=>{started=r;});
 const hold=new Promise(r=>{release=r;});
 const national=()=>({status:'available',coverage:51,periodStart:'2026-08',periodEnd:'2026-10',fetchedAt:new Date(now).toISOString(),rows:states.map(state=>({state,applications:10,priorApplications:5,unexpectedField:'must-not-persist'})),private:'must-not-persist'});
 const radar=()=>({status:'partial',sources:[{market:'Chicago, Illinois, US',kind:'license_records',status:'available',count:0,checkedAt:new Date(now).toISOString()},{market:'Miami-Dade County, Florida, US',kind:'recent_start_records',status:'unavailable',count:null}]});
 const opts={canWrite:()=>writable,clock:()=>now,readNational:async()=>{calls++;return national();},readRadar:async()=>radar()};
 let pending;
 try{
  // Disposable CI database only: prove the collector does not create missing schema.
  const missing=await createDurableMarketCycle({...opts,getPool:()=>a})();
  assert.equal(missing.outcome,'storage_unavailable');assert.equal(calls,0);
  const [[absent]]=await a.query("SELECT COUNT(*) AS n FROM information_schema.tables WHERE table_schema=DATABASE() AND table_name='sbc_public_market_evidence'");
  assert.equal(Number(absent.n),0);
  const migration=require('node:fs').readFileSync(require('node:path').join(__dirname,'../migrations/20261128_001_sbc_public_market_evidence.sql'),'utf8');
  await a.query(migration);
  const first=createDurableMarketCycle({...opts,getPool:()=>a,readNational:async()=>{calls++;started();await hold;return national();}});
  const second=createDurableMarketCycle({...opts,getPool:()=>b});
  pending=first();
  const timeout=AbortSignal.timeout(10000);
  await Promise.race([ready,new Promise((_,reject)=>timeout.addEventListener('abort',()=>reject(Error('collector did not acquire lock')),{once:true}))]);
  assert.equal((await second()).outcome,'busy');
  assert.equal(calls,1);
  release();
  assert.equal((await pending).persisted,true);
  const restart=createDurableMarketCycle({...opts,getPool:()=>b});
  assert.equal((await restart()).outcome,'not_due');assert.equal(calls,1);
  const [[row]]=await b.query('SELECT COUNT(*) AS n FROM sbc_public_market_evidence');
  assert.equal(Number(row.n),1);
  const [[stored]]=await b.query('SELECT evidence_json,outcome,next_ms FROM sbc_public_market_evidence');
  const evidence=JSON.parse(stored.evidence_json);
  assert.equal(stored.outcome,'partial');assert.equal(Number(stored.next_ms),now+300000);
  assert.equal(evidence.radar.sources.find(x=>x.kind==='license_records').count,0);
  assert.equal(evidence.radar.sources.find(x=>x.kind==='recent_start_records').count,null);
  assert.doesNotMatch(stored.evidence_json,/must-not-persist/);
  now+=300000;
  const revoke=createDurableMarketCycle({...opts,getPool:()=>a,readNational:async()=>{writable=false;return national();}});
  assert.equal((await revoke()).outcome,'writer_unavailable');
  const [[unchanged]]=await b.query('SELECT COUNT(*) AS n FROM sbc_public_market_evidence');
  assert.equal(Number(unchanged.n),1);
  writable=true;
  const recovered=await restart();
  assert.equal(recovered.persisted,true);assert.equal(recovered.delay,600000);
  const [[after]]=await b.query('SELECT COUNT(*) AS n FROM sbc_public_market_evidence');
  assert.equal(Number(after.n),2);
 }finally{release();if(pending)await pending.catch(()=>{});await Promise.all([a.end(),b.end()]);}
});
