'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'..'),read=p=>fs.readFileSync(path.join(root,p),'utf8');
const html=read('public/lead-research.html'),js=read('public/lead-research.js'),profile=read('public/sbc-lead-profile-v1.js'),csv=read('public/lead-research-import-core.js');
assert.match(html,/id="sbc-address-research-notice"/,'Lorna must see a persistent in-workspace address assignment notice');
assert.match(html,/Business address research/,'submission needs a dedicated address research section');
assert.match(html,/name="address"/,'reuse the existing canonical address field');
assert.match(html,/name="verificationSource"/,'address evidence must be recorded in the current source field');
assert.match(html,/data-go="add"/,'notice should take Lorna straight to lead entry');
assert.match(html,/id="sbc-address-missing-count"/,'research workspace should show missing-address count from assigned submissions');
assert.match(js,/Address needs research/,'submitted leads lacking an address should remain visibly incomplete');
assert.match(js,/sbc-address-missing-count/,'missing-address count should come from submitted CRM rows');
assert.match(js,/['"]address['"]/,'manual submit must include canonical address');
assert.match(js,/row\.record\.address/,'CSV preview must display address');
assert.match(csv,/address:\[/,'CSV must map address aliases');
assert.match(profile,/Research business address/,'Account 360 should open a research lookup while calling');
assert.match(profile,/google\.com\/maps\/search/,'address search is user-initiated and not treated as a verified result');
assert.match(profile,/noopener noreferrer/,'external research link must be isolated');
assert.match(profile,/c\.address/,'CRM must display a saved business address');
assert.equal(read('public/lead-research.html'),read('browser_public/lead-research.html'));
// The research script is intentionally served from public/ only; its HTML is mirrored.
assert.equal(profile,read('browser_public/sbc-lead-profile-v1.js'));
for(const name of ['public/lead-research.js','public/sbc-lead-profile-v1.js'])new vm.Script(read(name),{filename:name});
