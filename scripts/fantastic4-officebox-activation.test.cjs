'use strict';
const assert=require('node:assert/strict'),crypto=require('node:crypto');
const {buildPaidHandoff}=require('../enterprise/office-box-paid-handoff.cjs');
const C=require('../ecosystem/office-box-activation-client.cjs');
const order={id:'sbc_order_100',price:349,paymentStatus:'PAID',officeBoxSku:'OFFICE_BOX_BUSINESS',customerId:'sbc_customer_100',customerEmail:'owner@fixture.invalid'};
const payment={id:'square_payment_100',order_id:'square_order_100',location_id:'square_location_100',status:'COMPLETED',amount_money:{amount:34900,currency:'USD'}};
const parsed={squareOrderId:'square_order_100',squarePaymentId:'square_payment_100',squarePaymentStatus:'PAID',squarePaymentCompletedAt:'2026-10-27T10:00:00.000Z'};
const paymentRecord={sbcOrderId:order.id,squareOrderId:payment.order_id,squarePaymentId:payment.id,status:'PAID'};
const customer={id:'sbc_customer_100',businessName:'Fixture Test Co',ownerEmail:'owner@fixture.invalid'};
const paidEvent=buildPaidHandoff({order,parsed,payment,paymentRecord,expectedLocation:'square_location_100',customer,plan:'business'});
const secret='sbc-officebox-verification-secret-64-characters-long',nowSeconds=1793100000;
const input=C.makeLookup(paidEvent);
assert.equal(input.schema,'sbc.office-box.activation-lookup.v1');
assert.equal(input.customerId,order.customerId);
assert.equal(input.orderId,order.id);
const signed=C.signLookup(paidEvent,secret,{nowSeconds});
const expected=crypto.createHmac('sha256',secret).update(String(nowSeconds)+'.'+signed.body).digest('hex');
assert.equal(signed.headers['x-sbc-signature-v2'],'sha256='+expected);
assert.equal(signed.headers['x-sbc-signature'],undefined,'status lookup must require V2, never legacy');
const pending={ok:true,data:{schema:'sbc.office-box.activation-status.v1',correlationId:paidEvent.correlationId,status:'INVITATION_PENDING'}};
assert.deepEqual(C.verifyActivationLookup(paidEvent,pending),{status:'INVITATION_PENDING'});
assert.throws(()=>C.makeActiveEntitlement({paidEvent,activationResponse:pending,verifiedAt:'2026-10-27T10:00:00Z'}),/PENDING/);
const tenantId='tenant_'+('a'.repeat(16));
const activated={ok:true,data:{...pending.data,status:'ACTIVATED',tenantId,customerId:order.customerId,orderId:order.id,plan:'business'}};
assert.equal(C.verifyActivationLookup(paidEvent,activated).tenantId,tenantId);
for(const override of [{tenantId:'tenant_'+('b'.repeat(14))},{customerId:'other_customer_999'},{orderId:'other_order_999'},{plan:'starter'},{correlationId:'officebox_wrongid'}]){
 assert.throws(()=>C.verifyActivationLookup(paidEvent,{ok:true,data:{...activated.data,...override}}),/MISMATCH|UNTRUSTED/);
}
assert.throws(()=>C.verifyActivationLookup(paidEvent,{ok:true,data:{...pending.data,tenantId}}),/LEAK/);
const entitlement=C.makeActiveEntitlement({paidEvent,activationResponse:activated,verifiedAt:'2026-10-27T10:00:00Z'});
assert.equal(entitlement.schema,'sbc.office-box.entitlement.v1');
assert.equal(entitlement.status,'ACTIVE');
assert.equal(entitlement.paymentReference,payment.id);
assert.equal(entitlement.customerId,order.customerId);
assert.equal(entitlement.tenantId,tenantId);
assert.deepEqual(entitlement,C.makeActiveEntitlement({paidEvent,activationResponse:activated,verifiedAt:'2026-10-27T10:00:00Z'}));
const authorized=C.signActiveEntitlement(entitlement,secret,{nowSeconds});
assert.equal(authorized.path,'/api/sbc/entitlements');
assert.equal(authorized.headers['x-sbc-signature'],'sha256='+crypto.createHmac('sha256',secret).update(String(nowSeconds)+'.'+authorized.body).digest('hex'));
assert.throws(()=>C.signActiveEntitlement({...entitlement,status:'CANCELED'},secret,{nowSeconds}),/REFUSED/);
assert.throws(()=>C.signLookup(paidEvent,'weak'),/INVALID/);
assert.throws(()=>C.makeLookup({...paidEvent,eventType:'customer.provisioning.plan.created'}),/REQUIRED/);
console.log('FANTASTIC 4 OFFICE BOX ACTIVATION CONTRACT: PASS (signed V2, mapped tenant, pending/invalid refusal, deterministic verified entitlement)');
