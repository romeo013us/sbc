'use strict';
const assert = require('node:assert/strict');
const Factory = require('../enterprise/sbc-prospect-site-factory.cjs');
const prospect = (businessName,industry) => ({id:'quality-'+businessName.replace(/\W/g,'-'),slug:'quality-'+businessName.replace(/\W/g,'-').toLowerCase(),offerTier:'essentials',status:'Draft',industry,customer:{businessName,city:'Miami'}});
const tint=prospect('CJ Window Tinters','Window Tinting Service');
const salon=prospect('Velvet Hair Studio','Hair Salon');
const restaurant=prospect('Sunrise Kitchen','Restaurant');
const auto=prospect('Ace Auto Repair','Auto Repair');
const tintModel=Factory.define(tint);
assert.equal(tintModel.style.category,'tint','window-tinting deserves its own visual archetype');
assert.equal(tintModel.designVariant,Factory.define(tint).designVariant,'visual identity must remain deterministic');
const home=Factory.renderPage(tint,'home');
const salonHome=Factory.renderPage(salon,'home');
const foodHome=Factory.renderPage(restaurant,'home');
assert.match(home,/Tint consultation|Window film options/i,'tint-specific experience expected');
assert.match(home,/data-sbc-design-variant="tint-/);
assert.match(home,/noindex,nofollow,noarchive/,'private concepts must not be indexable');
assert.doesNotMatch(home,/5-star rated|certified installer|lifetime warranty|since 1990/i,'must not fabricate business claims');
assert.notEqual(home,salonHome,'industry archetypes cannot share generic templates');
assert.notEqual(salonHome,foodHome,'different categories require different content');
assert.match(Factory.renderPage(auto,'services'),/vehicle|maintenance|repair/i);
assert.match(Factory.renderPage(tint,'services'),/tint|film/i);
assert.match(Factory.renderPage(tint,'contact'),/does not submit, save, or transmit any visitor data/i);
assert.deepEqual(Factory.availablePages(tint),['home','services','about','contact']);
console.log('PASS: industry creative quality, deterministic tint design, no invented proof, noindex, correct tiers');
