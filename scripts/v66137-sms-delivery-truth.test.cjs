'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const sms=require('../enterprise/v66137-sms-delivery-truth.cjs');
const {patchServer,MARKER}=require('./v66137-stage-sms-delivery-truth.cjs');
const root=path.resolve(__dirname,'..'),read=p=>fs.readFileSync(path.join(root,p),'utf8');
const ref='SM'+'a'.repeat(32);
assert.equal(sms.destination('305-555-0123'),'+13055550123');
assert.equal(sms.destination('(305) 555-0123'),'+13055550123');
assert.equal(sms.destination('1 305 555 0123'),'+13055550123');
assert.equal(sms.destination('+442079460123'),'+442079460123');
for(const value of ['','abc','123','3055550123 x5','+1000'])assert.throws(()=>sms.destination(value));
assert.equal(sms.receipt({sid:ref,status:'queued'}).deliveryConfirmed,false);
assert.equal(sms.receipt({sid:ref,status:'sent'}).deliveryConfirmed,false);
assert.equal(sms.receipt({sid:ref,status:'delivered'}).deliveryConfirmed,true);
for(const value of [{status:'queued'},{sid:'bad',status:'sent'},{sid:ref,status:'undelivered'}])assert.throws(()=>sms.receipt(value));
assert.equal(sms.providerError({code:30034},400).code,'TWILIO_30034');
assert.match(sms.providerError({code:30034},400).message,/A2P 10DLC/);
assert.match(sms.providerError({code:30035},400).message,/registering/);
assert.match(sms.providerError({code:21610},400).message,/opted out/);
assert.equal(sms.isSuppressed({sbcSmsOptOut:true,status:'Customer'}),true);
assert.equal(sms.isSuppressed({smsOptOut:true,status:'Customer'}),true);
assert.equal(sms.isSuppressed({status:'Customer'}),false);
const input=read('server.js'),staged=patchServer(input);
assert(staged.includes(MARKER));
assert.equal(patchServer(staged),staged,'stage must be idempotent');
assert(staged.includes('SBC_V66137_SMS_TRUTH.destination(customer.phone)'));
assert(staged.includes('SBC_V66137_SMS_TRUTH.isSuppressed(customer)'));
assert(staged.includes('SBC_V66137_SMS_TRUTH.providerError(data,r.status)'));
assert(staged.includes('SBC_V66137_SMS_TRUTH.receipt(data)'));
assert(staged.includes("a2pRegistration:'NOT_VERIFIED_BY_SBC'"));
assert(!staged.includes("const data=await r.json(); if(!r.ok) throw new Error(data.message||'Twilio SMS failed.');"));
new vm.Script(staged,{filename:'staged-server.js'});
const pub=read('public/app.js'),mirror=read('browser_public/app.js');
assert.equal(pub,mirror);
assert.equal(pub.split('async function sendSmsToLead(id)').length-1,2);
assert(!pub.includes("toast('SMS sent')"));
assert(pub.includes('SMS submitted to Twilio'));
assert(pub.includes("e.target.elements.namedItem('body')"));
assert(!pub.includes("st.sms?.configured?'READY'"));
assert(!pub.includes("st.sms.configured?'READY'"));
new vm.Script(pub,{filename:'app.js'});
console.log('[SBC SMS V66137] PASS: phone normalization, provider evidence, A2P errors, suppression, staged server syntax and mirrored UI; no provider calls');
