assert.throws(malformed,/unclosed quotation/);
assert.throws(()=>core.preview(Array.from({length:101},(_,i)=>'Shop '+i).join('\n'),{format:'lines'}),/maximum of 100/);
const email=core.preview('Business Name,Email\nShop,invalid@@example');
assert.equal(email.records[0].status,'invalid');
assert.match(email.records[0].errors.join(' '),/Email/);
const unknown=core.preview('Shop One\nShop Two',{format:'lines'});
assert.equal(unknown.ready,2);
// CSV "Source" means prospect research evidence, not an oversized CRM channel.
const sourceShort='https://business-directory.example.com/listings/autobody';
const short=core.preview('Business Name,Phone,Source\nMiami Auto Body,3055550195,'+sourceShort);
assert.equal(short.ready,1);
assert.equal(short.records[0].record.source,'Lead Research - Bulk Import');
assert.equal(short.records[0].record.verificationSource,sourceShort);
const sourceMedium='https://directory.example.com/company/'+('a'.repeat(180));
assert.ok(sourceMedium.length>160&&sourceMedium.length<300);
const medium=core.preview('Business Name,Phone,Source\nRamos Auto Services,3055550196,'+sourceMedium);
assert.equal(medium.ready,1,'a 200+ character research URL should never be rejected as oversized CRM source');
assert.equal(medium.records[0].record.verificationSource,sourceMedium);
assert.equal(medium.records[0].record.source,'Lead Research - Bulk Import');
const sourceLong='https://listing.example.com/business/'+('referrer=maps&source=public&'.repeat(20));
assert.ok(sourceLong.length>300);
const longer=core.preview('Business Name,Phone,Notes,Source\n"Vital Auto Collision Center",3055550197,"Looked up storefront","'+sourceLong+'"');
assert.equal(longer.ready,1,'large source evidence should fit in notes');
assert.equal(longer.records[0].record.source,'Lead Research - Bulk Import');
assert.equal(longer.records[0].record.verificationSource.length,300);
assert.ok(longer.records[0].record.notes.includes(sourceLong),'full original source must not be lost');
assert.ok(longer.records[0].record.notes.startsWith('Looked up storefront\n\nOriginal research source (CSV): '));
assert.ok(longer.records[0].warnings.some(w=>w.includes('preserved in Notes')));
const overflow=core.preview('Business Name,Phone,Notes,Source\n"Euroautotech Solutions",3055550198,"'+('N'.repeat(1700))+'","'+sourceLong+'"');
assert.equal(overflow.ready,0,'reject rather than silently drop evidence if Notes cannot contain it');
assert.match(overflow.records[0].errors.join(' '),/source exceeds available Notes space/i);
const noSource=core.preview('Business Name,Phone\n"Example Motors",3055550199');
assert.equal(noSource.ready,1);
assert.equal(noSource.records[0].record.verificationSource,undefined,'never fabricate a research source');
assert.equal(noSource.records[0].record.source,'Lead Research - Bulk Import');

