const head='Business Name,Contact,Phone,Email,Website,Industry,Address,Notes\n'
+'Sunrise Barber Shop,Sam,3055551001,sam@example.com,barber.example,Barber,Miami,Google page\n'
+'Blue Cafe,Ada,3055551002,,blue.example,Restaurant,Hialeah,Checked website';
const parsed=core.preview(head,{format:'auto'});
assert.equal(parsed.total,2);
assert.equal(parsed.ready,2);
assert.equal(parsed.headersDetected,true);
assert.equal(parsed.records[0].record.businessName,'Sunrise Barber Shop');
assert.equal(parsed.records[1].record.phone,'3055551002');
assert.equal(parsed.records[1].record.source,'Lead Research - Bulk Import');
const quoted=core.preview('Business Name,Notes,Phone\n"Jane, Inc.","Quote ""carefully""\nSecond line",3055551003');
assert.equal(quoted.records[0].record.businessName,'Jane, Inc.');
assert.equal(quoted.records[0].record.notes,'Quote "carefully"\nSecond line');
const tabs=core.preview('Business Name\tPhone\nA Bakery\t3055551004\nB Bakery\t3055551005');
assert.equal(tabs.ready,2);
assert.equal(tabs.records[0].record.phone,'3055551004');
const names=core.preview('Island Spa\nIsland Restaurant\nIsland Law Office',{format:'lines'});
assert.equal(names.ready,3);
assert.equal(names.records[0].record.businessName,'Island Spa');
