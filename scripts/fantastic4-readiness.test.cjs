'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {assess}=require('./fantastic4-readiness.cjs');
const manifest=require('../ecosystem/fantastic4-manifest.json');
const sample=JSON.parse(fs.readFileSync(path.join(__dirname,'../ecosystem/fantastic4-evidence.sample.json'),'utf8'));
assert.equal(manifest.systems.mainSite.origin,'https://sbcmia.com');
assert.equal(manifest.systems.reseller.origin,'https://sbcwebsites.com');
assert.equal(manifest.commercial.checkoutRedirectIsPaid,false);
assert.equal(manifest.commercial.allowUnrelatedPurchaseToProvisionOfficeBox,false);
assert.deepEqual(manifest.commercial.officeBoxPlans.map(p=>'OFFICE_BOX_'+p.toUpperCase()),manifest.commercial.officeBoxSkus);
assert.deepEqual(manifest.states.workspaceWriteStates,['ACTIVE']);
assert.equal(assess(sample).status,'NO_GO');
const release={commandCenterCommit:'f'.repeat(40),officeBoxCommit:'e'.repeat(40),publishedRuntimeFingerprint:'sha256:'+'a'.repeat(64),verifiedMySqlBackupReceipt:'readback-restored-disposable-database',rollbackArtifactReceipt:'release-artifact-verified-fingerprint'};
const checks=manifest.goLiveRequirements.map(id=>({id,status:'PASS',checkedAt:'2026-10-27T22:00:00-04:00',evidence:'owner-reviewed proof at gate/'+id}));
assert.equal(assess({schema:sample.schema,release,checks}).status,'READY_FOR_OWNER_APPROVAL');
assert.equal(assess({schema:sample.schema,release,checks:[...checks,checks[0]]}).status,'NO_GO');
assert.equal(assess({schema:sample.schema,release,checks:checks.map((c,i)=>i===0?{...c,status:'FAIL'}:c)}).status,'NO_GO');
assert.equal(assess({schema:sample.schema,release,checks:checks.map((c,i)=>i===0?{...c,evidence:''}:c)}).status,'NO_GO');
assert.equal(assess({schema:sample.schema,release:{...release,publishedRuntimeFingerprint:''},checks}).status,'NO_GO');
console.log('FANTASTIC 4 READINESS CONTRACT: PASS (all missing/false/duplicate/unproven gates fail closed)');
