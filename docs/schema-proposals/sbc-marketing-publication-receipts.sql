CREATE TABLE sbc_core_marketing_publication_receipts (
 tenant_id BIGINT UNSIGNED NOT NULL,
 channel ENUM('facebook','instagram','linkedin','google_business') NOT NULL,
 account_ref VARCHAR(255) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 slot_local CHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 submission_id VARCHAR(80) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 provider_post_ref VARCHAR(255) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 provider_media_ref VARCHAR(255) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 slug VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 format ENUM('square','landscape','portrait') NOT NULL,
 revision INT UNSIGNED NOT NULL,
 sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 source_asset_id CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 manifest_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 verified_at DATETIME(3) NOT NULL,
 submitted_at DATETIME(3) NOT NULL,
 published_at DATETIME(3) NOT NULL,
 observed_at DATETIME(3) NOT NULL,
 PRIMARY KEY (tenant_id,channel,provider_post_ref),
 UNIQUE KEY uq_publication_slot (tenant_id,channel,account_ref,slot_local),
 UNIQUE KEY uq_publication_submission (tenant_id,submission_id),
 FOREIGN KEY (tenant_id,slug,format,revision,sha256) REFERENCES sbc_core_marketing_inventory(tenant_id,slug,format,revision,sha256),
 FOREIGN KEY (tenant_id,slug,format,revision,verified_at) REFERENCES sbc_core_marketing_readbacks(tenant_id,slug,format,revision,verified_at),
 CHECK (tenant_id>0 AND revision>0 AND verified_at<=submitted_at AND submitted_at<=published_at AND published_at<=observed_at)
) ENGINE=InnoDB;
